"""Generate independent test images, never read or change user originals. Requires Pillow."""
from pathlib import Path
from PIL import Image, ImageDraw

root = Path(__file__).resolve().parents[1] / 'test-data' / '图片边界 样本'
root.mkdir(parents=True, exist_ok=True)
(root / '.travel-generated-samples').write_text('generated by Travel-Recording verification', encoding='utf-8')
image = Image.new('RGB', (90, 60), '#e5eadf')
draw = ImageDraw.Draw(image)
draw.rectangle((0, 0, 35, 20), fill='red')
draw.rectangle((60, 40, 89, 59), fill='blue')
exif = Image.Exif()
exif[274] = 6  # Actual EXIF clockwise rotation, not a pre-rotated sample.
exif[36867] = '2023:03:09 10:20:30'
image.save(root / '方向6.JPG', exif=exif, quality=95)
image.save(root / '真实 WebP.webp', lossless=True)
transparent = Image.new('RGBA', (35, 70), (0, 0, 0, 0))
ImageDraw.Draw(transparent).ellipse((3, 3, 30, 30), fill=(40, 140, 100, 160))
transparent.save(root / '透明 竖图.png')
Image.new('RGB', (6000, 4000), '#8bb6a0').save(root / '大图.jpg', quality=90)
(root / '损坏.jpg').write_bytes(b'not an image')
(root / '跳过.txt').write_text('unsupported file is ignored', encoding='utf-8')
pages = root / '分页'
pages.mkdir(exist_ok=True)
for number in range(205):
    Image.new('RGB', (24, 16), (40, 100 + number % 100, 120)).save(pages / f'page-{number:03}.png')
print(root)
